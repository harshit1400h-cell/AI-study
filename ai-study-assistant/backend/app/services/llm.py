"""LLM provider abstraction layer supporting Google Gemini, OpenAI, and fallback."""

from abc import ABC, abstractmethod
from typing import Optional
from app.config import get_settings


class LLMProvider(ABC):
    """Abstract interface for large language model providers."""

    @abstractmethod
    def generate(self, prompt: str, system_instruction: str = "") -> str:
        """Generate a completion for the given prompt and optional system instruction.

        Args:
            prompt: User prompt content.
            system_instruction: System instructions/guidelines for the model.

        Returns:
            The raw text output from the model.
        """
        pass


class GeminiProvider(LLMProvider):
    """Google Gemini LLM provider using google-generativeai."""

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash") -> None:
        """Initialize Google Gemini client.

        Args:
            api_key: Google Gemini API key.
            model_name: Gemini model name.
        """
        self.api_key = api_key
        self.model_name = model_name
        import google.generativeai as genai
        genai.configure(api_key=self.api_key)
        self._genai = genai

    def generate(self, prompt: str, system_instruction: str = "") -> str:
        """Generate response via Gemini API."""
        try:
            model = self._genai.GenerativeModel(
                model_name=self.model_name,
                system_instruction=system_instruction if system_instruction else None,
            )
            response = model.generate_content(prompt)
            if response.text:
                return response.text
            return "No response generated by Gemini."
        except Exception as e:
            raise RuntimeError(f"Gemini API error: {str(e)}") from e


class OpenAIProvider(LLMProvider):
    """OpenAI LLM provider using the openai official client."""

    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini") -> None:
        """Initialize OpenAI client.

        Args:
            api_key: OpenAI API key.
            model_name: OpenAI model identifier.
        """
        self.api_key = api_key
        self.model_name = model_name
        from openai import OpenAI
        self.client = OpenAI(api_key=self.api_key)

    def generate(self, prompt: str, system_instruction: str = "") -> str:
        """Generate response via OpenAI Chat Completions API."""
        try:
            messages = []
            if system_instruction:
                messages.append({"role": "system", "content": system_instruction})
            messages.append({"role": "user", "content": prompt})

            response = self.client.chat.completions.create(
                model=self.model_name,
                messages=messages,
                temperature=0.3,
            )
            content = response.choices[0].message.content
            return content if content else ""
        except Exception as e:
            raise RuntimeError(f"OpenAI API error: {str(e)}") from e


class NoneProvider(LLMProvider):
    """Fallback provider when no LLM is configured."""

    def generate(self, prompt: str, system_instruction: str = "") -> str:
        """Return informative fallback notice."""
        return "LLM not configured. Set LLM_PROVIDER and API key in .env"


def get_llm_provider() -> LLMProvider:
    """Factory function returning the configured LLM provider instance."""
    settings = get_settings()
    provider_name = settings.LLM_PROVIDER.lower().strip()

    if provider_name == "gemini":
        if not settings.GOOGLE_API_KEY or "your_google_api_key" in settings.GOOGLE_API_KEY:
            return NoneProvider()
        return GeminiProvider(
            api_key=settings.GOOGLE_API_KEY,
            model_name=settings.GEMINI_MODEL,
        )
    elif provider_name == "openai":
        if not settings.OPENAI_API_KEY or "your_openai_api_key" in settings.OPENAI_API_KEY:
            return NoneProvider()
        return OpenAIProvider(
            api_key=settings.OPENAI_API_KEY,
            model_name=settings.OPENAI_MODEL,
        )
    else:
        return NoneProvider()

